// app/api/ai/intelligence/agents/rsiOptimizer.ts
import { ChatGoogleGenerativeAI } from '@langchain/google-genai';
import { parseAIJson } from '../helpers';

export async function runRSIOptimization(pastLogs: any[]) {
    const model = new ChatGoogleGenerativeAI({
        model: "gemini-3.1-flash-lite",
        temperature: 0.2,
    });

    // 🌟 1. 過去ログの事前ダイジェスト集計
    const summarizedLogs = pastLogs.slice(0, 8).map(log => {
        const trends = log.trend_insights || {};
        const profits = log.profitable_cards || {};
        const proof = log.proof_package;
        const chief = log.chief_package;

        const extractSlotSummary = (container: any) => {
            if (!container) return [];
            const result: any[] = [];
            ['us', 'eu', 'asia'].forEach((region) => {
                const rep = container[region];
                if (rep?.slots && Array.isArray(rep.slots)) {
                    rep.slots.forEach((s: any) => {
                        const firstItem = s.items?.[0];
                        if (firstItem) {
                            result.push({
                                region,
                                slot: s.slotKey,
                                card: firstItem.cardName,
                                buy: firstItem.currentJpPriceJPY || firstItem.jpBuyPriceJPY,
                                target: firstItem.targetMarketPrice || firstItem.targetSoldPrice,
                                spread: firstItem.priceSpreadJPY,
                                roi: firstItem.spreadROI || firstItem.growthRate
                            });
                        }
                    });
                }
            });
            return result;
        };

        return {
            date: log.created_at?.split('T')[0],
            mvp: chief?.mvpHighlight?.cardName || chief?.chosenCardOrItem,
            trendSamples: extractSlotSummary(trends),
            arbitrageSamples: extractSlotSummary(profits),
            hitProof: proof ? { card: proof.cardName, growth: proof.growthRate, pattern: proof.hitReasonPattern } : null
        };
    });

    const prompt = `あなたは越境トレカ・ホビー組織全体の【RSI（再帰的自己改善）最高監査・進化エンジン】です。
蓄積された過去の5スロット網羅ログおよび的中実績データを精査し、
各専門AI（トレンド、アービトラージ、SNSクリエイター）のプロンプトを自律強化するための「新ルール（学習ナレッジ）」を生成してください。

【分析対象ダイジェストログ（直近数週分）】:
${JSON.stringify(summarizedLogs, null, 2)}

【5大スロット監査基準】:
1. classic_vintage: クラシック・ヴィンテージ（旧裏〜PCG）
2. neo_vintage: ネオ・ヴィンテージ（DP〜XY絶版）
3. exclusive_promo: 限定プロモ・配布品
4. modern_meta: 現行モダン・大会メタ
5. graded_sealed: 高額鑑定・POP希少・未開封BOX

【3階層の自己改善タスク】:
1. 【トレンド層】どのスロット（ヴィンテージ、プロモ、POP希少等）が最も実成約・急騰に結びついているかを評価し、推奨重み付けを更新する。
2. 【アービトラージ層】実成約データとの乖離を防ぐため、国内外の単純価格スプレッドの信頼性と推奨最低スプレッド比率（%）を監査・算出する。
3. 【自律学習ルール生成】各エージェントのプロンプトに最優先で直接注入される、具体的で厳格な指示ルール（autoGeneratedRules）を各1件以上策定する。

必ず以下のJSON形式のみを出力してください（Markdown装飾や前後の解説テキストは不要です）:
{
  "overallEvaluation": "直近の予測精度とスプレッド査定に関する総合評価サマリー（全AIの合格点・改善点）",
  "accuracyScore": 85,
  "trendWeightAdjustments": {
    "recommendedPattern": "最も勝率の高いスロット名（例: exclusive_promo / classic_vintage）",
    "rationale": "実相場・的中実績データとの照合結果から導かれたスロット別重み付け調整理由"
  },
  "arbitrageSpreadAudits": {
    "spreadReliabilityScore": "スプレッド信頼性スコア (例: 高信頼 / 88点)",
    "recommendedMinimumSpread": "推奨最低スプレッド比率 (例: +40%以上)",
    "rationale": "海外実成約との乖離や流動性リスクを抑えるためのスプレッド根拠"
  },
  "autoGeneratedRules": [
    {
      "targetAgent": "trend",
      "ruleText": "【RSI自律改善】市場トレンド予測時は、[推奨スロット名]の重み付けを優先し、直近30日の海外取引速度の裏付けを必須とすること"
    },
    {
      "targetAgent": "arbitrage",
      "ruleText": "【RSI自律改善】サヤ査定時は、国内仕入れ値に対して海外実成約のスプレッドが[X]%以上開いている銘柄を厳選すること"
    },
    {
      "targetAgent": "sns",
      "ruleText": "【RSI自律改善】週間カレンダー投稿時は、月曜の看板投稿および各曜日投稿の1行目に『国内仕入額と現地実成約額の対比』を必ず数値で明記すること"
    }
  ]
}`;

    const res = await model.invoke(prompt);
    return parseAIJson(res.content.toString());
}