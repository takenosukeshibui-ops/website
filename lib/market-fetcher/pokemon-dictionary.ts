// 英語タイトル抽出用：英語名の文字数降順（例: MEWTWO -> MEW）
const SORTED_POKEMON_ENTRIES = Object.entries(POKEMON_EN_JA).sort(
  (a, b) => b[0].length - a[0].length
);

// 日本語からの逆引き用：日本語名の文字数降順（例: ブラッキー -> ラッキー、リザードン -> リザード）
const SORTED_JA_TO_EN_ENTRIES = Object.entries(POKEMON_EN_JA).sort(
  (a, b) => b[1].length - a[1].length
);

/**
 * eBayタイトルから該当するすべてのポケモン・トレーナー名を抽出し、日本語名配列で返す（複数セット検知用）
 */
export function extractAllPokemonNamesJa(ebayTitle: string): string[] {
  const found: string[] = [];
  let remaining = ebayTitle;

  for (const [enName, jaName] of SORTED_POKEMON_ENTRIES) {
    const escaped = enName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp(`(?<![A-Z0-9])${escaped}(?![A-Z0-9])`, 'gi');
    if (regex.test(remaining)) {
      if (!found.includes(jaName)) {
        found.push(jaName);
      }
      remaining = remaining.replace(regex, ' ');
    }
  }

  return found;
}

/**
 * eBayタイトルから英語のポケモン・トレーナー名を抽出し、日本語名に変換する
 */
export function extractPokemonNameJa(ebayTitle: string): string | null {
  const all = extractAllPokemonNamesJa(ebayTitle);
  return all.length > 0 ? all[0] : null;
}

/**
 * 日本語カード名から英語のポケモン・トレーナー名を逆引きする（eBay検索URL用）
 */
export function extractPokemonNameEn(jaCardName: string): string | null {
  for (const [enName, jaName] of SORTED_JA_TO_EN_ENTRIES) {
    if (jaCardName.includes(jaName)) {
      return enName
        .toLowerCase()
        .replace(/\b\w/g, (c) => c.toUpperCase());
    }
  }
  return null;
}